export function systemLabAnalyteCreateData(
  def: SystemLabAnalyteSeed,
): Prisma.LabAnalyteDefinitionCreateInput {
  return {
    key: def.key,
    label: def.label,
    abbreviation: def.abbreviation ?? null,
    unit: def.unit ?? null,
    panelGroup: def.panelGroup,
    sortOrder: def.sortOrder,
    referenceLow: dec(def.referenceLow),
    referenceHigh: dec(def.referenceHigh),
    referenceLowFemale: dec(def.referenceLowFemale),
    referenceHighFemale: dec(def.referenceHighFemale),
    referenceLowMale: dec(def.referenceLowMale),
    referenceHighMale: dec(def.referenceHighMale),
    referenceText: def.referenceText ?? null,
    sourceNote: def.sourceNote ?? null,
    isSystem: true,
    isActive: true,
  };
}

export function getSystemAnalyteByKey(key: string): SystemLabAnalyteSeed | undefined {
  return SYSTEM_LAB_ANALYTES.find((a) => a.key === key);
}